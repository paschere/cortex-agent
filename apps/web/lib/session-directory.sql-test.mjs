import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from '../node_modules/typescript/lib/typescript.js';
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const db = new PGlite();
await db.exec(`create type user_role as enum ('member','team_admin','org_admin');
create table ba_user(id text primary key,email text,name text);
create table ba_member("userId" text,"organizationId" text,role text);
create table users(id uuid primary key default gen_random_uuid(),organization_id text,email text,name text,role user_role not null);
create unique index dir_identity on users(organization_id,lower(email));
insert into ba_user values('alice','Alice@example.com','Alice');
insert into ba_member values('alice','new-company','owner'),('alice','other-company','member');`);
globalThis.__directoryPool = { query: (q,p) => db.query(q,p) };
let source = await readFile(new URL('./session-directory.ts', import.meta.url),'utf8');
source = source.replace(/import[\s\S]*?;\n/g,'');
source = 'const pool=globalThis.__directoryPool;\n'+source;
const { resolveSessionDirectory: resolve } = await import(`data:text/javascript;base64,${Buffer.from(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText).toString('base64')}`);
const arrivals = await Promise.all(Array.from({length:8},()=>resolve('alice','new-company')));
assert.equal(new Set(arrivals.map(row=>row.id)).size,1);
assert.equal(arrivals[0].role,'org_admin');
assert.equal((await db.query('select count(*)::int n from users')).rows[0].n,1);
await db.exec(`update users set email=lower(email); update ba_member set role='member' where "organizationId"='new-company'`);
assert.equal((await resolve('alice','new-company')).id,arrivals[0].id);
assert.equal((await resolve('alice','new-company')).role,'member');
await db.exec(`update users set role='team_admin'`);
assert.equal((await resolve('alice','new-company')).role,'team_admin');
assert.notEqual((await resolve('alice','other-company')).id,arrivals[0].id);
await db.exec(`delete from ba_member where "organizationId"='new-company'`);
assert.equal(await resolve('alice','new-company'),null);
assert.equal(await resolve('unknown-account','other-company'),null);
await db.exec('drop table users');
await assert.rejects(()=>resolve('alice','other-company'));
console.log('10 session directory SQL checks passed');
await db.close();
